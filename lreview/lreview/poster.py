"""Post collected kreview results to Gerrit via gerrit-cli.

Posting is pinned to the revision SHA that was actually reviewed (from
the summary manifest), so a patchset pushed while the review was running
gets the comments on the reviewed patchset, not silently on the new one.

Each entry is posted under the manifest lock with a fresh re-read of
its state, so concurrent lreview invocations can neither
double-post a review nor clobber each other's manifest updates.
"""

import json
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Optional

from .defaults import DEFAULT_PREFIX  # noqa: F401 (re-exported)
from .manifest import locked_summary, read_summary
from .runner import STATUS_CLEAN, STATUS_FINDINGS

DEFAULT_TAG = "autogenerated:ai-review"



def resolve_prefix(prefix: Optional[str], entry: dict) -> Optional[str]:
    """Resolve the message prefix for an entry.

    None falls back to DEFAULT_PREFIX; a literal "<model>" placeholder
    (default or custom, e.g. "[Marc Bot - AI review - <model>]") is
    replaced with the model that ran the review, falling back to the
    agent name when no model is known.
    """
    if prefix is None:
        prefix = DEFAULT_PREFIX
    model = entry.get("model") or entry.get("agent") or "AI"
    return prefix.replace("<model>", model)


@dataclass
class PostOutcome:
    number: object  # change number, or the slug for local reviews
    status: str  # posted | skipped | error
    detail: str = ""


def load_summary(results_dir: Path) -> dict:
    summary_path = results_dir / "summary.json"
    if not summary_path.is_file():
        raise FileNotFoundError(
            f"{summary_path} not found — run 'lreview run' first")
    return read_summary(results_dir)


def _is_postable_clean(entry: dict) -> bool:
    """A clean Gerrit review, which posts a no-issues message.

    GitHub reviews always write their result file, so a clean one is
    recorded as findings (zero of them) and posts its own message.
    """
    return (entry.get("status") == STATUS_CLEAN
            and entry.get("provider") != "github"
            and not entry.get("local"))


def clean_message(entry: dict) -> str:
    kind = "light review" if entry.get("mode") == "light" else "review"
    return f"Looks good: the {kind} found no issues in ps{entry['patchset']}."


def cover_message(entry: dict, spec: Optional[dict]) -> Optional[str]:
    """The review's top-level Gerrit message: the agent's verdict, or
    lreview's own for a clean review, plus the --memory iteration —
    so earlier findings not repeated here read as tracked, not
    forgotten."""
    message = clean_message(entry) if spec is None else spec.get("message")
    iteration = entry.get("memory_reviews")
    if iteration:
        note = (f"(review iteration {iteration} of this change, with "
                "accumulated review memory)")
        message = f"{message}\n\n{note}" if message else note
    return message


def _validated(results_dir: Path, entry: dict, spec: Optional[dict]):
    """(spec, cover line, held findings) after the VM verdicts: refuted
    findings come out, confirmed ones get a note (validate.py).  An
    entry with no validation comes back unchanged."""
    from .validate import apply_verdicts, cover_line, load_validation
    validation = load_validation(results_dir, entry) if spec else None
    if not validation:
        return spec, None, []
    new_spec, held = apply_verdicts(spec, validation)
    return new_spec, cover_line(validation), held


def _post_verdicts(results_dir: Path, entry: dict, dry_run: bool = False):
    """Post the VM verdicts of findings that are on Gerrit already:
    those of a review posted before its validation ran, or the AI-review
    threads a validation read from Gerrit.  Each verdict goes as a reply
    in its finding's thread, on that comment's revision, under the
    validation prefix.  A finding whose comment lreview cannot find
    gets a line in the patchset-level message instead.  Returns
    (success, detail)."""
    from gerrit_cli.client import GerritCommentsClient
    from gerrit_cli.reviewer import CodeReviewer
    from .validate import (load_validation, plan_replies, save_validation,
                           tested_sha, unposted, validation_prefix,
                           verdict_message)

    from .validate import private_note
    validation = load_validation(results_dir, entry)
    todo = unposted(validation)
    note = private_note(validation)
    if not todo:
        return False, "no confirmed or refuted verdict to post" + (
            f"; {note}" if note else "")
    client = GerritCommentsClient(url=entry["base_url"]) \
        if entry.get("base_url") else GerritCommentsClient()
    try:
        spec = json.loads((results_dir / entry["json"]).read_text())
    except (OSError, KeyError, TypeError, json.JSONDecodeError):
        spec = {}
    try:
        published = client.get_comments(entry["number"]) or {}
    except Exception:  # noqa: BLE001 - fall back to the message alone
        published = {}
    groups, unmatched = plan_replies(published, spec, validation,
                                     entry["sha"], DEFAULT_TAG)
    tested = tested_sha(validation) or entry["sha"]
    message = verdict_message(validation, unmatched)
    # The message goes with the replies on the tested revision, or
    # alone on it.
    posts = [(rev, files) for rev, files in groups.items()]
    if not any(rev == tested for rev, _ in posts):
        posts.append((tested, {}))
    replies = sum(len(r) for _, files in posts for r in files.values())
    detail = (f"VM verdicts for {len(todo)} finding(s), {replies} as "
              f"thread replies, in {len(posts)} post(s)"
              + (f"; {note}" if note else ""))
    if dry_run:
        return True, detail
    prefix = validation_prefix(validation, entry.get("validation"))
    reviewer = CodeReviewer(client=client)
    done = {i["id"] for i in unmatched}
    errors = []
    for rev, files in posts:
        ids = {r.pop("_id") for rs in files.values() for r in rs}
        result = reviewer.post_review(
            change_number=entry["number"], comments=files or None,
            message=message if rev == tested else None, vote=None,
            revision=rev, prefix=prefix, tag=DEFAULT_TAG)
        if result.success:
            done |= ids
        else:
            errors.append(result.error or "unknown error")
            if rev == tested:
                done -= {i["id"] for i in unmatched}
    for item in validation.get("findings") or []:
        if item["id"] in done:
            item["posted"] = True
    save_validation(results_dir, entry, validation)
    if errors:
        return False, "; ".join(errors)
    return True, detail


def _post_drafts(results_dir: Path, entry: dict, dry_run: bool = False):
    """Put the VM verdicts into the reviewer's own drafts, which the
    validation read.  The drafts stay drafts: lreview publishes
    nothing.  Returns (status, detail)."""
    from gerrit_cli.client import GerritCommentsClient
    from .validate import (_needs_baseline, draft_todo, load_validation,
                           plan_draft_updates, private_note,
                           private_reason, save_validation,
                           validation_prefix)
    validation = load_validation(results_dir, entry)
    if not draft_todo(validation):
        return "skipped", "no confirmed or refuted verdict to put in a draft"
    client = GerritCommentsClient(url=entry["base_url"]) \
        if entry.get("base_url") else GerritCommentsClient()
    drafts = client.get_drafts(entry["number"]) or {}
    prefix = validation_prefix(validation, entry.get("validation"))
    updates, missing = plan_draft_updates(drafts, validation, prefix)
    notes = [f"{item['id']}: {why}" for item, why in missing]
    note = private_note(validation)
    detail = (f"VM verdicts in {len(updates)} draft(s), not published"
              + (f"; skipped {'; '.join(notes)}" if notes else "")
              + (f"; {note}" if note else ""))
    if not updates:
        return "skipped", detail
    if dry_run:
        return "would post", detail
    errors = []
    for item, revision, draft_id, comment in updates:
        try:
            client.update_draft(entry["number"], revision, draft_id,
                                comment)
        except Exception as exc:  # noqa: BLE001 - the next draft
            errors.append(f"{item['id']}: {exc}")
            continue
        # A bug with no baseline run keeps no mark: the next validation
        # with the baseline retests it, and its proof can replace the
        # line in the draft.
        if not (private_reason(item, validation)
                and _needs_baseline(item, validation)):
            item["posted"] = True
    save_validation(results_dir, entry, validation)
    if errors:
        return "error", "; ".join(errors)
    return "posted", detail


def _mark_review_verdicts(results_dir: Path, entry: dict) -> None:
    """After a review went out with its verdicts applied: the confirmed
    notes are in it, and the refuted findings stay off Gerrit.  Neither
    needs a reply later.  A confirmed bug that must stay private was
    not in the review, so it keeps no mark."""
    from .validate import (load_validation, public_findings,
                           save_validation, POSTED)
    validation = load_validation(results_dir, entry)
    if not validation:
        return
    for item in public_findings(validation):
        if item["verdict"] in POSTED:
            item["posted"] = True
    save_validation(results_dir, entry, validation)


def _private_detail(results_dir: Path, entry: dict) -> str:
    from .validate import load_validation, private_note
    note = private_note(load_validation(results_dir, entry))
    return f"; {note}" if note else ""


def _validation_pending(results_dir: Path, entry: dict) -> bool:
    """Whether findings on Gerrit have VM verdicts still to post: only
    a confirmed or refuted verdict goes to Gerrit."""
    from .validate import load_validation, unposted
    return bool(unposted(load_validation(results_dir, entry)))


def _post_one(results_dir: Path, entry: dict, prefix: Optional[str]):
    """Post a single review; returns (success, detail, prefix used).

    prefix=None auto-stamps the default "[AI review - <model>]"; pass
    an empty string to post without any prefix.
    """
    from gerrit_cli.client import GerritCommentsClient
    from gerrit_cli.reviewer import CodeReviewer

    prefix = resolve_prefix(prefix, entry)

    spec = (None if _is_postable_clean(entry)
            else json.loads((results_dir / entry["json"]).read_text()))
    message = cover_message(entry, spec)
    spec, line, held = _validated(results_dir, entry, spec)
    if line:
        message = f"{message}\n\n{line}" if message else line

    # Post to the Gerrit host the change was reviewed from, not
    # whatever $GERRIT_URL happens to point at.
    client = None
    if entry.get("base_url"):
        client = GerritCommentsClient(url=entry["base_url"])
    reviewer = CodeReviewer(client=client)

    result = reviewer.post_review(
        change_number=entry["number"],
        comments=spec.get("comments") if spec else None,
        message=message,
        # posting metadata is lreview's, whatever the agent wrote into
        # its JSON: the review must not vote (review-prompts
        # gerrit-review.md), and the tag marks the comments as automation
        vote=None,
        revision=entry["sha"],
        prefix=prefix,
        tag=DEFAULT_TAG,
    )
    if result.success:
        detail = (f"no-issues message on ps{entry['patchset']}"
                  if spec is None else
                  f"{result.comments_posted} comment(s) on "
                  f"ps{entry['patchset']}")
        if held:
            detail += f", {len(held)} finding(s) held back"
        detail += _private_detail(results_dir, entry)
        if prefix:
            detail += f" as '{prefix}'"
        return True, detail, prefix
    return False, result.error or "unknown error", prefix


def _github_review(spec: dict, head_sha: str, prefix: Optional[str]):
    """The GitHub review a post sends, and a description of it: only
    inline findings become line comments, the rest join the body."""
    body = (prefix + "\n\n" if prefix else "") + spec.get("message", "")
    summary = []
    comments = []
    for finding in spec.get("findings", []):
        text = finding["message"]
        if finding.get("location_kind", "inline") == "inline":
            comments.append({"path": finding["path"], "line": finding["line"],
                             "side": finding.get("side", "RIGHT").upper(), "body": text})
        else:
            summary.append("- " + text)
    if summary:
        body += "\n\nAdditional findings:\n" + "\n".join(summary)
    payload = {"body": body, "commit_id": head_sha, "event": "COMMENT"}
    if comments: payload["comments"] = comments
    detail = f"{len(comments)} inline comment(s) pinned to {head_sha[:12]}"
    if summary:
        detail += f", {len(summary)} more finding(s) in the review body"
    return payload, detail


def _post_github(results_dir: Path, entry: dict, prefix: Optional[str]):
    """Post one neutral artifact, refusing a PR whose head moved."""
    from .github import github_request
    prefix = resolve_prefix(prefix, entry)
    owner_repo = entry["repository"]
    number = entry["number"]
    current = github_request(f"/repos/{owner_repo}/pulls/{number}")
    if current["head"]["sha"] != entry["head_sha"]:
        return False, "PR head changed since review; refusing stale post", prefix
    spec = json.loads((results_dir / entry["json"]).read_text())
    payload, detail = _github_review(spec, entry["head_sha"], prefix)
    github_request(f"/repos/{owner_repo}/pulls/{number}/reviews", "POST", payload)
    return True, f"posted {detail}", prefix


def _would_post_detail(results_dir: Path, entry: dict) -> str:
    """Describe what a real post would send, without contacting anyone."""
    if _is_postable_clean(entry):
        return f"no-issues message on ps{entry['patchset']}"
    spec = json.loads((results_dir / entry["json"]).read_text())
    if entry.get("provider") == "github":
        return _github_review(spec, entry["head_sha"], None)[1]
    spec, _line, held = _validated(results_dir, entry, spec)
    comments = spec.get("comments") or {}
    if isinstance(comments, dict):
        count = sum(len(v) for v in comments.values())
    else:
        count = len(comments)
    where = (f"ps{entry['patchset']}" if entry.get("patchset")
             else entry.get("head_sha", "")[:12])
    detail = f"{count} comment(s) on {where}"
    if held:
        detail += f", {len(held)} finding(s) held back"
    return detail + _private_detail(results_dir, entry)


def post_results(
    results_dir: Path,
    changes: Optional[list[int]] = None,
    prefix: Optional[str] = None,
    force: bool = False,
    dry_run: bool = False,
) -> list[PostOutcome]:
    """Post reviews to Gerrit.

    A review with findings posts its comments. A clean Gerrit review
    posts a no-issues message, but only when it is named in changes:
    without changes, every unposted entry in the manifest would get
    one, however old.

    Args:
        results_dir: Directory holding summary.json and review files.
        changes: Change numbers (or manifest keys) to post, clean or
            not; None posts every unposted review with findings.
        prefix: Text prepended to every message. None auto-stamps
            "[AI review - <model>]"; "" posts without a prefix.
        force: Post even if the manifest says it was already posted.
        dry_run: Report what would be posted, contacting no provider
            and leaving the manifest untouched.
    """
    snapshot = load_summary(results_dir)
    if changes:
        # A request may be an exact manifest key ("64620",
        # "64620-light") or a bare change number, which expands to
        # every mode's entry for that change.
        wanted = []
        missing = []
        for item in changes:
            name = str(item)
            if name in snapshot:
                wanted.append(name)
                continue
            expanded = [k for k in snapshot
                        if k == name or k.startswith(f"{name}-")]
            if expanded:
                wanted.extend(sorted(expanded))
            else:
                missing.append(name)
        if missing:
            raise KeyError(
                f"change(s) {', '.join(missing)} not found in "
                f"{results_dir}/summary.json")
    else:
        wanted = list(snapshot.keys())

    outcomes: list[PostOutcome] = []
    for key in wanted:
        # Re-read and post under the manifest lock: the guard and the
        # posted-flag update are atomic against concurrent invocations.
        with locked_summary(results_dir, save=not dry_run) as summary:
            entry = summary.get(key)
            if entry is None:
                outcomes.append(PostOutcome(
                    key, "skipped", "no longer in manifest"))
                continue
            number = entry["number"]

            if entry.get("local"):
                outcomes.append(PostOutcome(
                    key, "skipped",
                    "local review — not tied to a Gerrit change"))
                continue
            if _is_postable_clean(entry) and not changes:
                outcomes.append(PostOutcome(
                    number, "skipped",
                    "clean — name it to post a no-issues message "
                    f"(lreview post {key})"))
                continue
            if (entry["status"] != STATUS_FINDINGS
                    and not _is_postable_clean(entry)):
                outcomes.append(PostOutcome(
                    number, "skipped", f"status is '{entry['status']}'"))
                continue
            if entry.get("source") == "drafts":
                try:
                    status, detail = _post_drafts(
                        results_dir, entry, dry_run=dry_run)
                except Exception as exc:  # noqa: BLE001
                    status, detail = "error", str(exc)
                outcomes.append(PostOutcome(number, status, detail))
                continue
            from_gerrit = entry.get("source") == "gerrit"
            if ((entry.get("posted") or from_gerrit)
                    and (not force or from_gerrit)
                    and entry.get("provider") != "github"):
                # The findings are on Gerrit already: post the verdicts
                # alone, never the review a second time.  A review read
                # from Gerrit is someone's posted comments, so --force
                # does not post it again either.
                if not _validation_pending(results_dir, entry):
                    from .validate import load_validation, private_note
                    note = private_note(load_validation(results_dir, entry))
                    outcomes.append(PostOutcome(
                        number, "skipped",
                        ("no VM verdicts to post" if from_gerrit else
                         "already posted (use --force to repost)")
                        + (f"; {note}" if note else "")))
                    continue
                try:
                    success, detail = _post_verdicts(
                        results_dir, entry, dry_run=dry_run)
                except Exception as exc:  # noqa: BLE001
                    outcomes.append(PostOutcome(number, "error", str(exc)))
                    continue
                status = ("would post" if dry_run else
                          "posted" if success else "error")
                outcomes.append(PostOutcome(number, status, detail))
                continue
            if entry.get("posted") and not force:
                outcomes.append(PostOutcome(
                    number, "skipped",
                    "already posted (use --force to repost)"))
                continue

            if dry_run:
                outcomes.append(PostOutcome(
                    number, "would post",
                    _would_post_detail(results_dir, entry)))
                continue

            try:
                if entry.get("provider") == "github":
                    success, detail, used_prefix = _post_github(results_dir, entry, prefix)
                else:
                    success, detail, used_prefix = _post_one(results_dir, entry, prefix)
            except Exception as exc:  # noqa: BLE001 - one bad entry
                # (missing file, config error) must not kill the rest
                outcomes.append(PostOutcome(number, "error", str(exc)))
                continue

            if success:
                entry["posted"] = True
                entry["posted_at"] = datetime.now(timezone.utc).isoformat(
                    timespec="seconds")
                entry["posted_prefix"] = used_prefix
                _mark_review_verdicts(results_dir, entry)
                outcomes.append(PostOutcome(number, "posted", detail))
            else:
                outcomes.append(PostOutcome(number, "error", detail))

    return outcomes
