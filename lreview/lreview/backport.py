"""Backport detection for lreview.

A port to another branch carries Lustre-change: and Lustre-commit:
trailers that name the upstream change. A review of such a commit asks
a different question: is the commit an honest translation of the
upstream change? lreview adds backport-prompt.md to the review prompt
of these commits only, with the upstream commits already fetched and
the facts about each upstream change that Gerrit holds.
"""

import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Optional

from . import worktree as wt

BACKPORT_PROMPT_PATH = Path(__file__).resolve().parent / "backport-prompt.md"

_TRAILER_RE = re.compile(r"^Lustre-(change|commit):[ \t]*(.*?)[ \t]*$",
                         re.MULTILINE)
_HASH_RE = re.compile(r"\b[0-9a-f]{40}\b")
# Comments that an AI review posted carry this tag (gerrit-review.md).
AI_REVIEW_TAG = "autogenerated:ai-review"
# Keep the prompt small: a long thread list hides the rules.
MAX_THREADS = 20
MAX_THREAD_TEXT = 400


@dataclass
class Trailer:
    """One upstream change that the commit names."""
    url: Optional[str] = None
    commit: Optional[str] = None
    landed: bool = False  # False for "Lustre-commit: TBD ..."


@dataclass(frozen=True)
class ReviewThread:
    """An unresolved AI review comment on the upstream change."""
    path: str
    line: Optional[int]
    patchset: Optional[int]
    url: str
    message: str


@dataclass(frozen=True)
class GerritFacts:
    """What Gerrit says about the upstream change."""
    sha: str  # current patch set
    patchset: int
    status: str
    change_id: Optional[str]
    subject: str
    patchsets: dict  # sha -> patch set number, every revision
    threads: tuple = ()  # ReviewThread, only for a change not landed
    ref: str = ""
    fetch_urls: tuple = ()


@dataclass(frozen=True)
class Upstream:
    """An upstream change, and the commit to compare the port with."""
    name: str
    sha: Optional[str]  # None: lreview could not get the commit
    landed: bool
    ported_from: Optional[str] = None  # set when the port names another commit
    change_id: Optional[str] = None
    subject: Optional[str] = None
    patchset: Optional[int] = None  # the current patch set
    ported_patchset: Optional[int] = None  # None: not a patch set of it
    threads: tuple = field(default=())


def parse_trailers(body: str) -> list[Trailer]:
    """The upstream changes of a commit message, in order.

    A squashed port has one Lustre-change:/Lustre-commit: pair for each
    change. Older commits have some malformed values: these keep what
    they can, and the commit is still a port.
    """
    trailers: list[Trailer] = []
    for key, value in _TRAILER_RE.findall(body):
        found = _HASH_RE.search(value)
        commit = found.group() if found else None
        if key == "change":
            trailers.append(Trailer(
                url=value if "://" in value else None, commit=commit,
                landed=commit is not None))
        elif trailers and trailers[-1].commit is None:
            trailers[-1].commit = commit
            trailers[-1].landed = not value.upper().startswith("TBD")
        else:
            trailers.append(Trailer(
                commit=commit, landed=not value.upper().startswith("TBD")))
    return trailers


def open_ai_threads(comments: dict, comment_url) -> list[ReviewThread]:
    """The AI review threads that are still unresolved.

    A thread is unresolved when its newest comment is. comment_url
    turns a comment id into its web link.
    """
    by_id = {}
    for path, entries in (comments or {}).items():
        for entry in entries:
            by_id[entry["id"]] = (path, entry)

    def root_of(entry):
        seen = set()
        while entry.get("in_reply_to") in by_id and entry["id"] not in seen:
            seen.add(entry["id"])
            entry = by_id[entry["in_reply_to"]][1]
        return entry

    threads: dict[str, list] = {}
    for path, entry in by_id.values():
        threads.setdefault(root_of(entry)["id"], []).append((path, entry))
    found = []
    for root_id, entries in threads.items():
        entries.sort(key=lambda pe: pe[1].get("updated", ""))
        path, root = by_id[root_id]
        if (root.get("tag") or "") != AI_REVIEW_TAG:
            continue
        if not entries[-1][1].get("unresolved"):
            continue
        found.append(ReviewThread(
            path=path, line=root.get("line"), patchset=root.get("patch_set"),
            url=comment_url(root_id),
            message=" ".join(root.get("message", "").split())[:MAX_THREAD_TEXT]))
    found.sort(key=lambda t: (t.patchset or 0, t.path, t.line or 0))
    return found


def gerrit_facts(url: str, repo: Path) -> GerritFacts:
    """Ask Gerrit about the upstream change behind a Lustre-change URL."""
    from gerrit_cli.client import GerritCommentsClient

    base_url, number = GerritCommentsClient.parse_gerrit_url(url)
    client = GerritCommentsClient(url=base_url)
    detail = client.get_change_detail(number)
    sha = detail["current_revision"]
    revision = detail["revisions"][sha]
    project = detail["project"]
    threads = ()
    if detail.get("status") != "MERGED":
        web = client.format_change_url(project, number)
        threads = tuple(open_ai_threads(
            client.get_comments(number),
            lambda cid: f"{web}/comment/{cid}/"))
    return GerritFacts(
        sha=sha, patchset=revision["_number"],
        status=detail.get("status", ""), change_id=detail.get("change_id"),
        subject=detail.get("subject", ""),
        patchsets={s: r["_number"] for s, r in detail["revisions"].items()},
        threads=threads, ref=revision.get("ref", ""),
        fetch_urls=tuple(wt.gerrit_remote_urls(repo, base_url, project)
                         + [f"{base_url.rstrip('/')}/{project}"]))


def _local(repo: Path, trailer: Trailer, name: str) -> Upstream:
    """An upstream change known only from the commit in repo."""
    if trailer.commit is None or not wt.commit_exists(repo, trailer.commit):
        return Upstream(name, None, trailer.landed)
    return Upstream(name, trailer.commit, trailer.landed,
                    change_id=wt.commit_change_id(repo, trailer.commit),
                    subject=wt.commit_subject(repo, trailer.commit))


def _resolve(repo: Path, trailer: Trailer) -> Upstream:
    """Make the upstream commit of one trailer available in repo."""
    name = trailer.url or trailer.commit or "an unnamed upstream change"
    if (trailer.landed and trailer.commit
            and wt.commit_exists(repo, trailer.commit)):
        return _local(repo, trailer, name)
    try:
        facts = gerrit_facts(trailer.url, repo) if trailer.url else None
        if facts is not None and not wt.commit_exists(repo, facts.sha):
            wt.fetch_change(repo, list(facts.fetch_urls), facts.ref)
    except Exception:  # noqa: BLE001 - offline, or no access: use the hash
        facts = None
    if facts is None:
        return _local(repo, trailer, name)
    moved = (not trailer.landed and trailer.commit is not None
             and trailer.commit != facts.sha)
    return Upstream(
        name, facts.sha, facts.status == "MERGED",
        ported_from=trailer.commit if moved else None,
        change_id=facts.change_id, subject=facts.subject,
        patchset=facts.patchset,
        ported_patchset=facts.patchsets.get(trailer.commit),
        threads=facts.threads)


def detect(repo: Path, sha: str) -> Optional[list[Upstream]]:
    """The upstream changes of a commit, or None if it is not a port."""
    body = wt.run_git(repo, "log", "-1", "--format=%B", sha).stdout
    trailers = parse_trailers(body)
    if not trailers:
        return None
    return [_resolve(repo, trailer) for trailer in trailers]


def _describe(upstream: Upstream) -> list[str]:
    if upstream.sha is None:
        return [f"- {upstream.name}: lreview could not get this commit. "
                "Try to find it yourself."]
    lines = [f"- {upstream.name}"]
    if upstream.subject:
        lines.append(f"  - Subject: {upstream.subject}")
    if upstream.change_id:
        lines.append(f"  - Change-Id: {upstream.change_id}")
    if upstream.landed:
        lines.append(f"  - Landed as commit {upstream.sha}.")
    else:
        current = (f" (patch set {upstream.patchset})"
                   if upstream.patchset else "")
        lines.append(f"  - Not landed. Current commit {upstream.sha}{current}.")
    if upstream.ported_from:
        if upstream.ported_patchset:
            where = f"patch set {upstream.ported_patchset} of this change"
        elif upstream.patchset:
            where = "a commit that is no patch set of this change"
        else:
            where = "another commit"
        lines.append(f"  - The port names {upstream.ported_from}: {where}.")
    if upstream.threads:
        lines.append("  - Unresolved AI review comments on this change:")
        for thread in upstream.threads[:MAX_THREADS]:
            where = thread.path + (f":{thread.line}" if thread.line else "")
            ps = f" (patch set {thread.patchset})" if thread.patchset else ""
            lines.append(f"    - {where}{ps} {thread.url}")
            lines.append(f"      {thread.message}")
        if len(upstream.threads) > MAX_THREADS:
            lines.append(f"    - {len(upstream.threads) - MAX_THREADS} more; "
                         "read them on the change.")
    return lines


def backport_prompt(upstreams: list[Upstream]) -> str:
    """The prompt section for a review of a port."""
    lines = ["This commit is a backport of:"]
    for upstream in upstreams:
        lines += _describe(upstream)
    compare = ["  git " + " ".join(_range_diff(u.sha))
               for u in upstreams if u.sha]
    if compare:
        lines += ["", "Compare the port with upstream:", *compare]
    if len(upstreams) > 1:
        lines += ["", "The commit squashes these changes: together, they "
                      "are the upstream side of the comparison."]
    return "\n".join(lines) + "\n\n" + BACKPORT_PROMPT_PATH.read_text()


def _range_diff(sha: str) -> list[str]:
    from .since import range_diff_args
    return range_diff_args(sha, "HEAD")


def compaction_note(upstreams: list[Upstream]) -> str:
    """What a review needs to hear again after a compaction."""
    shas = ", ".join(u.sha or u.name for u in upstreams)
    return (f"This commit is a backport of {shas}. Re-read the backport "
            f"rules {BACKPORT_PROMPT_PATH} and follow them.")
