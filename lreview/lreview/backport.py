"""Backport detection for lreview.

A port to another branch carries Lustre-change: and Lustre-commit:
trailers that name the upstream change. A review of such a commit asks
a different question: is the commit an honest translation of the
upstream change? lreview adds backport-prompt.md to the review prompt
of these commits only, with the upstream commits already fetched and
the facts about each upstream change that Gerrit holds.

A port that lost its trailers is still a port, and its missing
trailers (often with a new Change-Id) are the defect a review has to
catch. A change on any other branch than upstream master without
trailers is looked up by Change-Id and by subject: on master first,
then on the other branches, since a patch can be ported from one
release branch to another without a master change.  The Change-Id of
the same patch is the same on every branch.
"""

import re
from dataclasses import dataclass, field, replace
from pathlib import Path
from typing import Optional

from . import worktree as wt

BACKPORT_PROMPT_PATH = Path(__file__).resolve().parent / "backport-prompt.md"

_TRAILER_RE = re.compile(r"^Lustre-(change|commit):[ \t]*(.*?)[ \t]*$",
                         re.MULTILINE)
_HASH_RE = re.compile(r"\b[0-9a-f]{40}\b")
_CHANGE_ID_RE = re.compile(r"^Change-Id:[ \t]*(I[0-9a-f]{40})[ \t]*$",
                           re.MULTILINE)
# "LU-12345 osd: ..." and "ABC-678 osd: ..." port the same change
_TICKET_RE = re.compile(r"^[A-Z][A-Z0-9]*-\d+\s+")
UPSTREAM_PROJECT = "fs/lustre-release"
UPSTREAM_BRANCH = "master"
# Shorter subjects ("tests: fix typo") match unrelated changes
MIN_SUBJECT_MATCH = 20
MAX_UNMARKED = 3
# Comments that an AI review posted carry this tag (gerrit-review.md).
AI_REVIEW_TAG = "autogenerated:ai-review"
# Keep the prompt small: a long thread list hides the rules.
MAX_THREADS = 20
MAX_THREAD_TEXT = 400


@dataclass
class Trailer:
    """One upstream change that the commit names."""
    url: Optional[str] = None
    commit: Optional[str] = None
    landed: bool = False  # False for "Lustre-commit: TBD ..."


@dataclass(frozen=True)
class ReviewThread:
    """An unresolved AI review comment on the upstream change."""
    path: str
    line: Optional[int]
    patchset: Optional[int]
    url: str
    message: str


@dataclass(frozen=True)
class GerritFacts:
    """What Gerrit says about the upstream change."""
    sha: str  # current patch set
    patchset: int
    status: str
    change_id: Optional[str]
    subject: str
    patchsets: dict  # sha -> patch set number, every revision
    threads: tuple = ()  # ReviewThread, only for a change not landed
    ref: str = ""
    fetch_urls: tuple = ()


@dataclass(frozen=True)
class Upstream:
    """An upstream change, and the commit to compare the port with."""
    name: str
    sha: Optional[str]  # None: lreview could not get the commit
    landed: bool
    ported_from: Optional[str] = None  # set when the port names another commit
    change_id: Optional[str] = None
    subject: Optional[str] = None
    patchset: Optional[int] = None  # the current patch set
    ported_patchset: Optional[int] = None  # None: not a patch set of it
    threads: tuple = field(default=())
    # Set when the port has no trailers: what matched it with this
    # upstream change, "Change-Id" or "subject"
    unmarked: Optional[str] = None
    # "<project> <branch>" when the change is not on upstream master
    branch: Optional[str] = None
    port_change_id: Optional[str] = None
    # Another change on the port's branch that has the upstream Change-Id
    change_id_taken_by: Optional[str] = None
    main: bool = False  # of a squashed port: the change the rest is for


def parse_trailers(body: str) -> list[Trailer]:
    """The upstream changes of a commit message, in order.

    A squashed port has one Lustre-change:/Lustre-commit: pair for each
    change. Older commits have some malformed values: these keep what
    they can, and the commit is still a port.
    """
    trailers: list[Trailer] = []
    for key, value in _TRAILER_RE.findall(body):
        found = _HASH_RE.search(value)
        commit = found.group() if found else None
        if key == "change":
            trailers.append(Trailer(
                url=value if "://" in value else None, commit=commit,
                landed=commit is not None))
        elif trailers and trailers[-1].commit is None:
            trailers[-1].commit = commit
            trailers[-1].landed = not value.upper().startswith("TBD")
        else:
            trailers.append(Trailer(
                commit=commit, landed=not value.upper().startswith("TBD")))
    return trailers


def open_ai_threads(comments: dict, comment_url) -> list[ReviewThread]:
    """The AI review threads that are still unresolved.

    A thread is unresolved when its newest comment is. comment_url
    turns a comment id into its web link.
    """
    by_id = {}
    for path, entries in (comments or {}).items():
        for entry in entries:
            by_id[entry["id"]] = (path, entry)

    def root_of(entry):
        seen = set()
        while entry.get("in_reply_to") in by_id and entry["id"] not in seen:
            seen.add(entry["id"])
            entry = by_id[entry["in_reply_to"]][1]
        return entry

    threads: dict[str, list] = {}
    for path, entry in by_id.values():
        threads.setdefault(root_of(entry)["id"], []).append((path, entry))
    found = []
    for root_id, entries in threads.items():
        entries.sort(key=lambda pe: pe[1].get("updated", ""))
        path, root = by_id[root_id]
        if (root.get("tag") or "") != AI_REVIEW_TAG:
            continue
        if not entries[-1][1].get("unresolved"):
            continue
        found.append(ReviewThread(
            path=path, line=root.get("line"), patchset=root.get("patch_set"),
            url=comment_url(root_id),
            message=" ".join(root.get("message", "").split())[:MAX_THREAD_TEXT]))
    found.sort(key=lambda t: (t.patchset or 0, t.path, t.line or 0))
    return found


def gerrit_facts(url: str, repo: Path) -> GerritFacts:
    """Ask Gerrit about the upstream change behind a Lustre-change URL."""
    from gerrit_cli.client import GerritCommentsClient

    base_url, number = GerritCommentsClient.parse_gerrit_url(url)
    client = GerritCommentsClient(url=base_url)
    detail = client.get_change_detail(number)
    sha = detail["current_revision"]
    revision = detail["revisions"][sha]
    project = detail["project"]
    threads = ()
    if detail.get("status") != "MERGED":
        web = client.format_change_url(project, number)
        threads = tuple(open_ai_threads(
            client.get_comments(number),
            lambda cid: f"{web}/comment/{cid}/"))
    return GerritFacts(
        sha=sha, patchset=revision["_number"],
        status=detail.get("status", ""), change_id=detail.get("change_id"),
        subject=detail.get("subject", ""),
        patchsets={s: r["_number"] for s, r in detail["revisions"].items()},
        threads=threads, ref=revision.get("ref", ""),
        fetch_urls=tuple(wt.gerrit_remote_urls(repo, base_url, project)
                         + [f"{base_url.rstrip('/')}/{project}"]))


def _local(repo: Path, trailer: Trailer, name: str) -> Upstream:
    """An upstream change known only from the commit in repo."""
    if trailer.commit is None or not wt.commit_exists(repo, trailer.commit):
        return Upstream(name, None, trailer.landed)
    return Upstream(name, trailer.commit, trailer.landed,
                    change_id=wt.commit_change_id(repo, trailer.commit),
                    subject=wt.commit_subject(repo, trailer.commit))


def _resolve(repo: Path, trailer: Trailer) -> Upstream:
    """Make the upstream commit of one trailer available in repo."""
    name = trailer.url or trailer.commit or "an unnamed upstream change"
    if (trailer.landed and trailer.commit
            and wt.commit_exists(repo, trailer.commit)):
        return _local(repo, trailer, name)
    try:
        facts = gerrit_facts(trailer.url, repo) if trailer.url else None
        if facts is not None and not wt.commit_exists(repo, facts.sha):
            wt.fetch_change(repo, list(facts.fetch_urls), facts.ref)
    except Exception:  # noqa: BLE001 - offline, or no access: use the hash
        facts = None
    if facts is None:
        return _local(repo, trailer, name)
    moved = (not trailer.landed and trailer.commit is not None
             and trailer.commit != facts.sha)
    return Upstream(
        name, facts.sha, facts.status == "MERGED",
        ported_from=trailer.commit if moved else None,
        change_id=facts.change_id, subject=facts.subject,
        patchset=facts.patchset,
        ported_patchset=facts.patchsets.get(trailer.commit),
        threads=facts.threads)


def subject_tail(subject: str) -> str:
    """The subject without its ticket, as master and a port share it."""
    return _TICKET_RE.sub("", subject.strip(), count=1)


def needs_upstream_search(change) -> bool:
    """A Gerrit change that is not on upstream master can be a port."""
    project = getattr(change, "project", None)
    if not project or not getattr(change, "number", None):
        return False
    branch = getattr(change, "branch", None)
    return not (project == UPSTREAM_PROJECT and branch == UPSTREAM_BRANCH)


def _search(client, scope: str, change_id: Optional[str],
            subject: str, exclude: int, limit: int = 10,
            before: Optional[str] = None) -> dict:
    """Changes in scope with change_id or the same subject tail, created
    before the time before: a newer change ports the commit, not the
    other way round."""
    found: dict[int, tuple[dict, str]] = {}
    queries = []
    if change_id:
        queries.append((f"{scope} change:{change_id}", "Change-Id"))
    tail = subject_tail(subject)
    if len(tail) >= MIN_SUBJECT_MATCH and '"' not in tail:
        queries.append((f'{scope} message:"{tail}"', "subject"))
    for query, how in queries:
        for hit in client.search_changes(f"{query} -change:{exclude}",
                                         limit=limit, options=[]):
            if how == "subject" and subject_tail(
                    hit.get("subject", "")) != tail:
                continue
            if before and hit.get("created", "") > before:
                continue
            found.setdefault(hit["_number"], (hit, how))
    return found


def find_unmarked(repo: Path, change, subject: str,
                  change_id: Optional[str], client=None) -> list[Upstream]:
    """The changes that a commit without trailers ports.

    A master change wins: a port names only master. Without one, the
    same patch on another branch is the source to compare with. A
    match by Change-Id is the same patch for sure; one by subject
    (ticket aside) can be a coincidence, which the review tells by
    comparing the diffs.
    """
    from gerrit_cli.client import GerritCommentsClient

    client = client or GerritCommentsClient(url=change.base_url)
    created = getattr(change, "created", None)
    found = _search(client, f"project:{UPSTREAM_PROJECT} "
                            f"branch:{UPSTREAM_BRANCH} -status:abandoned",
                    change_id, subject, change.number, before=created)
    if not found:
        found = {
            number: entry for number, entry in _search(
                client, "-status:abandoned", None, subject,
                change.number, before=created).items()
            if (entry[0].get("project"), entry[0].get("branch"))
            != (change.project, change.branch)}
    upstreams = []
    for number, (hit, how) in sorted(found.items())[:MAX_UNMARKED]:
        url = client.format_change_url(hit["project"], number)
        on_master = (hit["project"] == UPSTREAM_PROJECT
                     and hit.get("branch", UPSTREAM_BRANCH)
                     == UPSTREAM_BRANCH)
        upstream = _resolve(repo, Trailer(url=url))
        upstreams.append(replace(
            upstream, unmarked=how, port_change_id=change_id,
            branch=None if on_master
            else f"{hit['project']} {hit.get('branch')}"))
    return upstreams


def change_id_taken(change, change_id: str, client=None) -> Optional[str]:
    """Another change on the branch of change that uses change_id."""
    from gerrit_cli.client import GerritCommentsClient

    client = client or GerritCommentsClient(url=change.base_url)
    for hit in client.search_changes(
            f"project:{change.project} branch:{change.branch} "
            f"change:{change_id} -change:{change.number}",
            limit=1, options=[]):
        return client.format_change_url(hit["project"], hit["_number"])
    return None


def _check_change_ids(upstreams: list[Upstream], change) -> list[Upstream]:
    """Note where the upstream Change-Id is already used on the branch:
    the one reason a port may have its own."""
    checked = []
    for upstream in upstreams:
        if (upstream.change_id and upstream.port_change_id
                and upstream.change_id != upstream.port_change_id
                and change is not None and getattr(change, "branch", None)):
            try:
                taken = change_id_taken(change, upstream.change_id)
            except Exception:  # noqa: BLE001 - the review checks by hand
                taken = None
            upstream = replace(upstream, change_id_taken_by=taken)
        checked.append(upstream)
    return checked


def find_main(upstreams: list[Upstream], subject: str,
              change_id: Optional[str]) -> Optional[int]:
    """The index of the change that a squashed port is of.

    The port has its subject and its Change-Id. The order of the
    trailers says nothing: people list it first or last. None when
    neither matches: the upstream changes can be squashed into a patch
    that only the port's branch has.
    """
    tail = subject_tail(subject)
    same_subject = [i for i, u in enumerate(upstreams)
                    if u.subject and subject_tail(u.subject) == tail]
    same_id = [i for i, u in enumerate(upstreams)
               if change_id and u.change_id == change_id]
    both = [i for i in same_subject if i in same_id]
    for found in (both, same_subject, same_id):
        if found:
            return found[0]
    return None


def detect(repo: Path, sha: str, change=None) -> Optional[list[Upstream]]:
    """The upstream changes of a commit, or None if it is not a port.

    With change (a Gerrit change), a commit without trailers is also
    looked up on upstream master and the other branches.
    """
    body = wt.run_git(repo, "log", "-1", "--format=%B", sha).stdout
    ids = _CHANGE_ID_RE.findall(body)
    port_change_id = ids[-1] if ids else None
    trailers = parse_trailers(body)
    subject = body.split("\n", 1)[0]
    if not trailers:
        if change is None or not needs_upstream_search(change):
            return None
        upstreams = find_unmarked(repo, change, subject, port_change_id)
    else:
        upstreams = [_resolve(repo, trailer) for trailer in trailers]
        squash = len(upstreams) > 1
        main = (find_main(upstreams, subject, port_change_id) if squash
                else 0)
        if main is not None:
            upstreams[main] = replace(upstreams[main], main=squash,
                                      port_change_id=port_change_id)
    return _check_change_ids(upstreams, change) or None


def _describe(upstream: Upstream) -> list[str]:
    if upstream.sha is None:
        return [f"- {upstream.name}: lreview could not get this commit. "
                "Try to find it yourself."]
    lines = [f"- {upstream.name}"]
    if upstream.unmarked and upstream.branch:
        lines.append(f"  - Found on {upstream.branch} by its "
                     f"{upstream.unmarked}. Master has no such change, so "
                     "the port needs no Lustre-change:/Lustre-commit: "
                     "trailers.")
    elif upstream.unmarked:
        lines.append(f"  - Found on master by its {upstream.unmarked}: the "
                     "port has no Lustre-change:/Lustre-commit: trailers.")
    if upstream.subject:
        lines.append(f"  - Subject: {upstream.subject}")
    if upstream.change_id:
        lines.append(f"  - Change-Id: {upstream.change_id}")
    if (upstream.change_id and upstream.port_change_id
            and upstream.change_id != upstream.port_change_id):
        lines.append(f"  - The port's Change-Id is "
                     f"{upstream.port_change_id}: it differs.")
        if upstream.change_id_taken_by:
            lines.append(f"  - The upstream Change-Id is already used on "
                         f"the port's branch by "
                         f"{upstream.change_id_taken_by}.")
    if upstream.landed:
        lines.append(f"  - Landed as commit {upstream.sha}.")
    else:
        current = (f" (patch set {upstream.patchset})"
                   if upstream.patchset else "")
        lines.append(f"  - Not landed. Current commit {upstream.sha}{current}.")
    if upstream.ported_from:
        if upstream.ported_patchset:
            where = f"patch set {upstream.ported_patchset} of this change"
        elif upstream.patchset:
            where = "a commit that is no patch set of this change"
        else:
            where = "another commit"
        lines.append(f"  - The port names {upstream.ported_from}: {where}.")
    if upstream.threads:
        lines.append("  - Unresolved AI review comments on this change:")
        for thread in upstream.threads[:MAX_THREADS]:
            where = thread.path + (f":{thread.line}" if thread.line else "")
            ps = f" (patch set {thread.patchset})" if thread.patchset else ""
            lines.append(f"    - {where}{ps} {thread.url}")
            lines.append(f"      {thread.message}")
        if len(upstream.threads) > MAX_THREADS:
            lines.append(f"    - {len(upstream.threads) - MAX_THREADS} more; "
                         "read them on the change.")
    return lines


def backport_prompt(upstreams: list[Upstream]) -> str:
    """The prompt section for a review of a port."""
    if any(u.unmarked for u in upstreams):
        lines = ["This commit has no Lustre-change:/Lustre-commit: "
                 "trailers, but it looks like a port of (see "
                 "\"Ports without trailers\" below):"]
    else:
        lines = ["This commit is a backport of:"]
    for upstream in upstreams:
        lines += _describe(upstream)
    compare = ["  git " + " ".join(_range_diff(u.sha))
               for u in upstreams if u.sha]
    if compare:
        lines += ["", "Compare the port with upstream:", *compare]
    if len(upstreams) > 1 and not any(u.unmarked for u in upstreams):
        lines += ["", "The commit squashes these changes: together, they "
                      "are the upstream side of the comparison."]
        main = next((u for u in upstreams if u.main), None)
        lines.append(f"The main change is {main.name}." if main else
                     "None of them has the port's subject or Change-Id, so "
                     "the main change is unknown: it can be a patch of this "
                     "branch only. Do not report the Change-Id.")
    return "\n".join(lines) + "\n\n" + BACKPORT_PROMPT_PATH.read_text()


def _range_diff(sha: str) -> list[str]:
    from .since import range_diff_args
    return range_diff_args(sha, "HEAD")


def compaction_note(upstreams: list[Upstream]) -> str:
    """What a review needs to hear again after a compaction."""
    shas = ", ".join(u.sha or u.name for u in upstreams)
    return (f"This commit is a backport of {shas}. Re-read the backport "
            f"rules {BACKPORT_PROMPT_PATH} and follow them.")
