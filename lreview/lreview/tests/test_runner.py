    def test_stale_registration_is_pruned(self, repo, tmp_path, stub_claude):
        """A registered worktree whose dir was deleted out-of-band must
        not block future reviews of the same change."""
        import shutil
        # The exact path prepare_worktree will use for this change
        dest = tmp_path / "worktrees" / f"kreview_501_ps1.{os.getpid()}"
        subprocess.run(
            ["git", "-C", str(repo), "worktree", "add", "--detach",
             str(dest), "HEAD"], capture_output=True, check=True)
        shutil.rmtree(dest)

        sha = _git(repo, "rev-parse", "HEAD")
        config = _config(repo, tmp_path)
        results = run_batch(config, [_change(501, sha)])
        assert results[0].status == STATUS_CLEAN

    def test_local_refs_in_worktrees(self, repo, tmp_path, stub_claude):
        from lreview.gerrit import LocalChange
        sha = _commit_with_marker(
            repo, "HAS_FINDINGS", json.dumps(REVIEW_SPEC))
