class TestProgressTracker:

    def test_status_line(self, tmp_path):
        from lreview.runner import ProgressTracker
        log = tmp_path / "kreview-64086_ps40.log"
        log.write_text("x" * 2048)

        tracker = ProgressTracker(total=3)
        assert tracker.status_line() is None  # nothing running yet

        tracker.start("64086_ps40", log)
        tracker.start("64087_ps12", tmp_path / "missing.log")
        line = tracker.status_line()
        assert "64086_ps40 0m00s 2KB" in line
        assert "64087_ps12 0m00s" in line
        assert "done 0/3" in line

        tracker.finish("64086_ps40")
        line = tracker.status_line()
        assert "64086_ps40" not in line
        assert "done 1/3" in line

        tracker.finish("64087_ps12")
        assert tracker.status_line() is None

    def test_status_line_shows_live_tokens(self, tmp_path):
        from lreview.runner import ProgressTracker
        log = tmp_path / "kreview-64086_ps40.log"
        log.write_text(
            '{"type":"system","subtype":"estimated_tokens",'
            '"estimated_tokens":1000}\n'
            '{"type":"system","subtype":"estimated_tokens",'
            '"estimated_tokens":842000}\n')
        tracker = ProgressTracker(total=1)
        tracker.start("64086_ps40", log)
        assert "64086_ps40 0m00s 842k tok" in tracker.status_line()


class TestTokenParsing:

    def test_format_tokens(self):
        from lreview.runner import format_tokens
        assert format_tokens(None) is None
        assert format_tokens(999) == "999"
        assert format_tokens(53010) == "53k"
        assert format_tokens(2_140_000) == "2.1M"

    def test_live_token_count_sums_usage_events(self, tmp_path):
        """The live counter sums per-message usage, deduplicated by
        message id (later lines for the same id win)."""
        from lreview.runner import live_token_count
        log = tmp_path / "usage.log"
        log.write_text(
            '{"type":"assistant","message":{"id":"m1","usage":'
            '{"input_tokens":4,"cache_creation_input_tokens":100,'
            '"cache_read_input_tokens":1000,"output_tokens":1}}}\n'
            '{"type":"assistant","message":{"id":"m1","usage":'
            '{"input_tokens":4,"cache_creation_input_tokens":100,'
            '"cache_read_input_tokens":1000,"output_tokens":50}}}\n'
            '{"type":"assistant","message":{"id":"m2","usage":'
            '{"input_tokens":2,"cache_creation_input_tokens":0,'
            '"cache_read_input_tokens":2000,"output_tokens":10}}}\n'
            'not json at all\n')
        # m1 counted once (last wins): 4+100+1000+50, m2: 2+0+2000+10
        assert live_token_count(log) == 1154 + 2012

    def test_live_token_count_latest_wins(self, tmp_path):
        from lreview.runner import live_token_count
        log = tmp_path / "x.log"
        log.write_text(
            '{"type":"system","subtype":"estimated_tokens",'
            '"estimated_tokens":1000,"estimated_tokens_delta":10}\n'
            '{"type":"assistant","message":{}}\n'
            '{"type":"system","subtype":"estimated_tokens",'
            '"estimated_tokens":84200,"estimated_tokens_delta":20}\n')
        assert live_token_count(log) == 84200
        assert live_token_count(tmp_path / "missing.log") is None

    def test_parse_final_usage(self, tmp_path):
        from lreview.runner import parse_final_usage
        log = tmp_path / "x.log"
        log.write_text(
            '{"type":"system","subtype":"init"}\n'
            '{"type":"result","total_cost_usd":4.2,"usage":'
            '{"input_tokens":5,"cache_creation_input_tokens":100,'
            '"cache_read_input_tokens":900,"output_tokens":45}}\n')
        tokens, cost = parse_final_usage(log)
        assert tokens == 1050
        assert cost == 4.2

    def test_parse_final_usage_codex_turn_completed(self, tmp_path):
        """codex reports usage once, at the end of the turn; its
        input_tokens already include the cached ones, so the total is
        input + output (13064 here, not 23048)."""
        from lreview.runner import parse_final_usage
        log = tmp_path / "x.log"
        log.write_text(
            "Reading additional input from stdin...\n"
            '{"type":"thread.started","thread_id":"01a0"}\n'
            '{"type":"turn.started"}\n'
            '{"type":"item.completed","item":{"id":"item_0",'
            '"type":"agent_message","text":"done"}}\n'
            '{"type":"turn.completed","usage":{"input_tokens":12914,'
            '"cached_input_tokens":9984,"cache_write_input_tokens":0,'
            '"output_tokens":150,"reasoning_output_tokens":0}}\n')
        tokens, cost = parse_final_usage(log)
        assert tokens == 13064
        # a ChatGPT-plan run has no dollar figure to report
        assert cost is None

    def test_live_token_count_falls_back_to_codex_usage(self, tmp_path):
        """No per-message usage during a codex run — the total shows up
        only once turn.completed lands."""
        from lreview.runner import live_token_count
        log = tmp_path / "x.log"
        log.write_text('{"type":"item.completed","item":{"id":"item_0",'
                       '"type":"command_execution"}}\n')
        assert live_token_count(log) is None
        with open(log, "a") as f:
            f.write('{"type":"turn.completed","usage":'
                    '{"input_tokens":900,"cached_input_tokens":800,'
                    '"output_tokens":100}}\n')
        assert live_token_count(log) == 1000

    def test_parse_final_usage_absent(self, tmp_path):
        from lreview.runner import parse_final_usage
        log = tmp_path / "x.log"
        log.write_text("plain text log with no result event\n")
        assert parse_final_usage(log) == (None, None)
        assert parse_final_usage(tmp_path / "missing.log") == (None, None)


