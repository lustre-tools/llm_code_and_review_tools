class TestUpdateSummary:

    def _result(self, number, sha, status=STATUS_FINDINGS, ps=2):
        from lreview.runner import ReviewResult
        change = ResolvedChange(
            number=number, project="p", subject="s", sha=sha,
            patchset=ps, ref="r", base_url="https://gerrit.invalid")
        return ReviewResult(change, status, findings=1)

    def test_posted_survives_same_sha_rereview(self, tmp_path):
        update_summary(tmp_path, [self._result(700, "a" * 40)])
        summary = json.loads((tmp_path / "summary.json").read_text())
        summary["700"]["posted"] = True
        summary["700"]["posted_at"] = "2026-01-01T00:00:00+00:00"
        (tmp_path / "summary.json").write_text(json.dumps(summary))

        update_summary(tmp_path, [self._result(700, "a" * 40)])
        summary = json.loads((tmp_path / "summary.json").read_text())
        assert summary["700"]["posted"] is True
        assert summary["700"]["posted_at"] == "2026-01-01T00:00:00+00:00"

    def test_new_patchset_resets_posted_keeps_history(self, tmp_path):
        update_summary(tmp_path, [self._result(701, "a" * 40, ps=2)])
        summary = json.loads((tmp_path / "summary.json").read_text())
        summary["701"]["posted"] = True
        summary["701"]["posted_at"] = "2026-01-01T00:00:00+00:00"
        (tmp_path / "summary.json").write_text(json.dumps(summary))

        update_summary(tmp_path, [self._result(701, "b" * 40, ps=3)])
        summary = json.loads((tmp_path / "summary.json").read_text())
        assert summary["701"]["posted"] is False
        assert summary["701"]["last_posted"]["sha"] == "a" * 40
        assert summary["701"]["last_posted"]["patchset"] == 2

    def test_failed_rereview_keeps_posted_history(self, tmp_path):
        update_summary(tmp_path, [self._result(702, "a" * 40, ps=2)])
        summary = json.loads((tmp_path / "summary.json").read_text())
        summary["702"]["posted"] = True
        (tmp_path / "summary.json").write_text(json.dumps(summary))

        update_summary(
            tmp_path,
            [self._result(702, "b" * 40, status=STATUS_FAILED, ps=3)])
