# Behavior is driven by marker files in the worktree (cwd). A completed
# analysis always writes review-metadata.json (as review-core.md
# mandates); NO_METADATA simulates a claude run that bailed out early.
STUB_CLAUDE = """#!/bin/bash
if [ -n "$STUB_ARGS_LOG" ]; then printf '%s\\n' "$@" -- >> "$STUB_ARGS_LOG"; fi
case " $* " in *" --resume "*)
    if [ -n "$STUB_NO_SESSION" ]; then
        echo "No conversation found with session ID: gone" >&2; exit 1
    fi;;
esac
echo '{"type":"system","subtype":"init","session_id":"'"${STUB_SESSION:-sess-1}"'"}'
if [ -f FAIL_MARKER ]; then echo "boom"; exit 3; fi
if [ -f SLEEP_MARKER ]; then sleep 30; exit 0; fi
if [ -f NO_METADATA_MARKER ]; then echo "bailed early"; exit 0; fi
SEV=none
if [ -f HAS_FINDINGS ]; then SEV=high; fi
printf '{"author":"a","sha":"s","subject":"t","issues-found":0,\
"issue-severity-score":"%s","issue-severity-explanation":"e"}' "$SEV" \
    > review-metadata.json
if [ -f INVALID_MARKER ]; then printf '{oops' > gerrit-review.json; exit 0; fi
if [ -f ARRAY_MARKER ]; then printf '[]' > gerrit-review.json; exit 0; fi
if [ -f HAS_FINDINGS ]; then cp HAS_FINDINGS gerrit-review.json; fi
if [ -f RESULT_MARKER ]; then cp RESULT_MARKER review-result.json; fi
echo '{"type":"system","subtype":"estimated_tokens","estimated_tokens":123456}'
echo "Assisted-by: ClaudeCode:claude-fable-5"
echo '{"type":"result","result":"done","total_cost_usd":1.23,"usage":{"input_tokens":10,"cache_creation_input_tokens":1000,"cache_read_input_tokens":50000,"output_tokens":2000}}'
"""


def _git(repo: Path, *args: str) -> str:
    result = subprocess.run(
        ["git", "-C", str(repo), *args], capture_output=True, text=True)
    assert result.returncode == 0, result.stderr
    return result.stdout.strip()


@pytest.fixture
def stub_claude(tmp_path, monkeypatch):
    bin_dir = tmp_path / "bin"
    bin_dir.mkdir()
    stub = bin_dir / "claude"
    stub.write_text(STUB_CLAUDE)
    stub.chmod(stub.stat().st_mode | stat.S_IEXEC)
    monkeypatch.setenv("PATH", f"{bin_dir}{os.pathsep}{os.environ['PATH']}")
    return stub


