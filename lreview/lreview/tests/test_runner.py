class TestRunBatch:

    def test_findings_clean_failed_invalid(self, repo, tmp_path, stub_claude):
        sha_findings = _commit_with_marker(
            repo, "HAS_FINDINGS", json.dumps(REVIEW_SPEC))
        sha_clean = _git(repo, "rev-parse", "HEAD")
        sha_failed = _commit_with_marker(repo, "FAIL_MARKER")
        sha_invalid = _commit_with_marker(repo, "INVALID_MARKER")

        changes = [
            _change(101, sha_findings),
            _change(102, sha_clean),
            _change(103, sha_failed),
            _change(104, sha_invalid),
        ]
        config = _config(repo, tmp_path, jobs=4)
        results = {r.change.number: r for r in run_batch(config, changes)}

        assert results[101].status == STATUS_FINDINGS
        assert results[101].findings == 3
        assert results[101].severity == "high"
        assert results[101].model == "fable"  # parsed from Assisted-by
        assert results[101].tokens == 53010   # from the result event
        assert results[101].cost_usd == 1.23
        assert results[102].status == STATUS_CLEAN
        assert results[102].severity == "none"
        assert results[103].status == STATUS_FAILED
        assert results[104].status == STATUS_INVALID_JSON

        # Collected artifacts are per-change suffixed and valid
        collected = config.results_dir / "gerrit-review-101_ps1.json"
        assert json.loads(collected.read_text()) == REVIEW_SPEC
        # Human-readable markdown report generated for findings
        md = config.results_dir / "markdown" / "101_change_101_ps1.md"
        assert md.is_file()
        assert "## Findings" in md.read_text()
        assert results[101].markdown_path == md
        metadata = config.results_dir / "review-metadata-101_ps1.json"
        assert json.loads(
            metadata.read_text())["issue-severity-score"] == "high"
        # Invalid output is preserved for debugging
        assert (config.results_dir / "gerrit-review-104_ps1.invalid").exists()
        # Logs exist per change
        assert (config.results_dir / "kreview-103_ps1.log").exists()

        # Worktrees were cleaned up
        assert not any((tmp_path / "worktrees").glob("kreview_*"))

        # Summary manifest records everything
        summary = json.loads(
            (config.results_dir / "summary.json").read_text())
        assert summary["101"]["status"] == STATUS_FINDINGS
        assert summary["101"]["findings"] == 3
        assert summary["101"]["severity"] == "high"
        assert summary["101"]["model"] == "fable"
        assert summary["101"]["tokens"] == 53010
        assert summary["101"]["cost_usd"] == 1.23
        assert summary["101"]["markdown"] == "markdown/101_change_101_ps1.md"
        assert summary["101"]["sha"] == sha_findings
        assert summary["101"]["posted"] is False
        assert summary["102"]["status"] == STATUS_CLEAN
        assert summary["103"]["error"] == "claude exited 3"

