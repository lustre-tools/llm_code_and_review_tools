def _commit_with_marker(repo: Path, name: str, content: str = "") -> str:
    """Create a commit adding a marker file; return its SHA."""
    _git(repo, "checkout", "-q", "--detach", "HEAD")
    marker = repo / name
    marker.write_text(content)
    _git(repo, "add", name)
    _git(repo, "commit", "-q", "-m", f"add {name}")
    sha = _git(repo, "rev-parse", "HEAD")
    _git(repo, "rm", "-q", name)
    _git(repo, "commit", "-q", "-m", f"remove {name}")
    return sha


def _change(number: int, sha: str) -> ResolvedChange:
    return ResolvedChange(
        number=number, project="test/repo", subject=f"change {number}",
        sha=sha, patchset=1, ref=change_ref(number, 1),
        base_url="https://gerrit.invalid")


