    def _run_once(self, config, worktree, monkeypatch, verdicts,
                  vcfg=None, change=None):
        """One validation of SPEC's defects with the given verdicts;
        returns the IDs the validator was asked about and the record."""
        asked = []

        def fake_run(cmd, cwd, log_path, *a):
            log_path.write_text("")
            asked.extend(sorted(set(
                __import__("re").findall(r'"id": "(F\d+)"',
                                         cmd[2].split('### Findings')[1]))))
            items = []
            for fid in asked:
                d = cwd / "validation" / fid
                d.mkdir(parents=True)
                (d / "repro.sh").write_text("true")
                (d / "report.md").write_text("# r")
                items.append({"id": fid, "verdict": verdicts[fid],
                              "reproducer": f"{fid}/repro.sh"})
            (cwd / "validation.json").write_text(
                json.dumps({"findings": items}))
            return 0

        monkeypatch.setattr("lreview.runner._run_agent", fake_run)
        record = v.validate_change(config, vcfg or v.ValidateConfig(),
                                   change or _change(), worktree, SPEC)
        return asked, record

