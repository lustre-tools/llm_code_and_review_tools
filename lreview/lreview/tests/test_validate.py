class TestSelect:

    def test_defects_in_file_then_comment_order(self):
        found = v.select_findings(SPEC, ("defect",))
        assert [(f.id, f.file, f.line, f.index) for f in found] == [
            ("F1", "lustre/a.c", 3, 0),
            ("F2", "lustre/b.c", 9, 1),
        ]

    def test_notes_never_selected(self):
        found = v.select_findings(SPEC, v.MARKERS)
        assert all(f.line != 5 for f in found)

    def test_unmarked_counts_as_minor_and_range_gives_line(self):
        found = v.select_findings(SPEC, ("minor",))
        assert [(f.file, f.line) for f in found] == [
            ("lustre/a.c", 12), ("lustre/b.c", 7)]

    def test_no_comments(self):
        assert v.select_findings(None, ("defect",)) == []
        assert v.select_findings({"comments": []}, ("defect",)) == []

    def test_earlier_ids_are_kept_and_new_ones_follow(self):
        first = v.select_findings(SPEC, ("defect",))
        ids = {f.key: f.id for f in first}
        # Swap the IDs, as if an earlier run had numbered them so.
        ids = dict(zip(ids, reversed(list(ids.values()))))
        spec = json.loads(json.dumps(SPEC))
        spec["comments"]["lustre/c.c"] = [
            {"line": 1, "message": "(defect) new", "unresolved": True}]
        found = v.select_findings(spec, ("defect",), ids=ids)
        assert [(f.id, f.file) for f in found] == [
            ("F1", "lustre/b.c"), ("F2", "lustre/a.c"), ("F3", "lustre/c.c")]

    def test_key_follows_the_text(self):
        spec = json.loads(json.dumps(SPEC))
        spec["comments"]["lustre/a.c"][0]["message"] = "(defect) other bug"
        old = {f.file: f.key for f in v.select_findings(SPEC, ("defect",))}
        new = {f.file: f.key for f in v.select_findings(spec, ("defect",))}
        assert old["lustre/b.c"] == new["lustre/b.c"]
        assert old["lustre/a.c"] != new["lustre/a.c"]

    def test_reviewed_revision_recorded(self):
        found = v.select_findings(SPEC, ("defect",),
                                  v.Revision(sha="a" * 40, patchset=3))
        assert {(f.reviewed_sha, f.reviewed_patchset) for f in found} == {
            ("a" * 40, 3)}


def _gc(id, path_line=3, **over):
    c = {"id": id, "line": path_line, "tag": "autogenerated:ai-review",
         "patch_set": 2, "commit_id": "b" * 40, "unresolved": True,
         "message": "**[AI review - opus]**\n\n(defect) NULL deref",
         "updated": "2026-11-20 10:00:00.000000000"}
    c.update(over)
    return c


class TestGerritFindings:

    def test_unresolved_ai_threads_become_findings(self):
        comments = {
            "lustre/a.c": [
                _gc("r1"),
                # resolved by the author's last reply
                _gc("r2", 9, message="(defect) gone"),
                _gc("x2", 9, tag=None, in_reply_to="r2", unresolved=False,
                    message="Done", updated="2026-11-21 10:00:00.0"),
                # a human's own thread
                _gc("h1", 20, tag=None, message="(defect) human"),
                # reopened by a reply: still open
                _gc("r3", 30, unresolved=False, message="(minor) small"),
                _gc("x3", 30, tag=None, in_reply_to="r3", unresolved=True,
                    message="No, still wrong",
                    updated="2026-11-22 10:00:00.0"),
            ],
            "/PATCHSET_LEVEL": [_gc("p1", None, message="cover")],
        }
        spec = v.gerrit_findings_spec(comments, "autogenerated:ai-review")
        assert spec["source"] == "gerrit"
        got = [(e["gerrit_id"], e["message"])
               for e in spec["comments"]["lustre/a.c"]]
        assert got == [("r1", "(defect) NULL deref"),
                       ("r3", "(minor) small")]
        assert "/PATCHSET_LEVEL" not in spec["comments"]
        found = v.select_findings(spec, ("defect", "minor"))
        assert [(f.id, f.gerrit_id, f.cls, f.reviewed_sha,
                 f.reviewed_patchset) for f in found] == [
            ("F1", "r1", "defect", "b" * 40, 2),
            ("F2", "r3", "minor", "b" * 40, 2)]
        assert found[0].key == "r1"

    def test_commit_from_patchset_map(self):
        spec = v.gerrit_findings_spec(
            {"x.c": [_gc("r1", commit_id=None)]}, "autogenerated:ai-review",
            {2: "e" * 40})
        assert spec["comments"]["x.c"][0]["commit_id"] == "e" * 40


class TestNormalize:

    def test_missing_and_unknown_verdicts_are_inconclusive(self):
        found = v.select_findings(SPEC, ("defect",))
        out = v.normalize({"findings": [
            {"id": "F2", "verdict": "probably"}]}, found, "validator exited 1")
        by_id = {i["id"]: i for i in out["findings"]}
        assert by_id["F1"]["verdict"] == "inconclusive"
        assert "no verdict" in by_id["F1"]["note"]
        assert "validator exited 1" in by_id["F1"]["note"]
        assert by_id["F1"]["summary"] == ""
        assert by_id["F2"]["verdict"] == "inconclusive"
        assert "unknown verdict" in by_id["F2"]["note"]

    def test_valid_entry_kept_with_selection_fields(self, tmp_path):
        (tmp_path / "F1").mkdir()
        (tmp_path / "F1" / "out.txt").write_text("oops")
        (tmp_path / "F1" / "report.md").write_text("# report")
        found = v.select_findings(SPEC, ("defect",))
        out = v.normalize({"target": "rocky9", "findings": [
            {"id": "F1", "verdict": "confirmed", "method": "fail_loc",
             "summary": "oops", "evidence": "F1/out.txt",
             "steps": ["1. create", "2. run"], "actual": "LBUG",
             "file": "spoofed.c"}]}, found, evidence_root=tmp_path)
        item = out["findings"][0]
        assert item["verdict"] == "confirmed"
        assert item["method"] == "fail_loc"
        assert item["file"] == "lustre/a.c"
        assert item["comment_index"] == 0
        assert item["evidence"] == ["F1/out.txt"]
        assert item["report"] == "F1/report.md"
        assert item["steps"] == "1. create\n2. run"
        assert item["actual"] == "LBUG"
        assert item["posted"] is False
        assert out["target"] == "rocky9"

    def test_unknown_method_dropped(self):
        found = v.select_findings(SPEC, ("defect",))[:1]
        out = v.normalize({"findings": [
            {"id": "F1", "verdict": "not-testable", "method": "vibes"}]},
            found)
        assert out["findings"][0]["method"] is None

    @pytest.mark.parametrize("verdict", ["confirmed", "refuted"])
    def test_decisive_verdict_needs_a_file(self, tmp_path, verdict):
        found = v.select_findings(SPEC, ("defect",))[:1]
        given = {"findings": [{"id": "F1", "verdict": verdict,
                               "summary": "trust me",
                               "reproducer": "F1/repro.sh",
                               "evidence": ["../../etc/passwd"]}]}
        out = v.normalize(given, found, evidence_root=tmp_path)
        item = out["findings"][0]
        assert item["verdict"] == "inconclusive"
        assert "no reproducer or evidence file" in item["note"]
        (tmp_path / "F1").mkdir()
        (tmp_path / "F1" / "repro.sh").write_text("true")
        # A missing QA report keeps the verdict, with a note.
        out = v.normalize(given, found, evidence_root=tmp_path)
        item = out["findings"][0]
        assert item["verdict"] == verdict
        assert "no QA report" in item["note"]
        assert item["report"] is None
        (tmp_path / "F1" / "report.md").write_text("# report")
        out = v.normalize(given, found, evidence_root=tmp_path)
        assert out["findings"][0]["verdict"] == verdict
        assert out["findings"][0]["note"] is None
        assert out["findings"][0]["report"] == "F1/report.md"

    def test_obsolete_needs_an_older_reviewed_revision(self, tmp_path):
        (tmp_path / "F1").mkdir()
        (tmp_path / "F1" / "obsolete.diff").write_text("-old")
        given = {"findings": [{"id": "F1", "verdict": "obsolete",
                               "summary": "removed in ps3",
                               "evidence": ["F1/obsolete.diff"]}]}
        tested = v.Revision(sha="t" * 40, patchset=3)
        same = v.select_findings(SPEC, ("defect",), tested)[:1]
        out = v.normalize(given, same, evidence_root=tmp_path, tested=tested)
        assert out["findings"][0]["verdict"] == "inconclusive"
        assert "reviewed on the tested revision" in out["findings"][0]["note"]
        older = v.select_findings(SPEC, ("defect",),
                                  v.Revision(sha="r" * 40, patchset=2))[:1]
        out = v.normalize(given, older, evidence_root=tmp_path, tested=tested)
        # An obsolete verdict needs no QA report, only the diff.
        assert out["findings"][0]["verdict"] == "obsolete"

    def test_inconclusive_needs_no_file(self):
        found = v.select_findings(SPEC, ("defect",))[:1]
        out = v.normalize({"findings": [
            {"id": "F1", "verdict": "inconclusive", "summary": "no hit"}]},
            found)
        assert out["findings"][0]["verdict"] == "inconclusive"
        assert out["findings"][0]["note"] is None


def _validation(verdicts, root=None):
    """A normalized validation of SPEC's defects on patchset 2, with
    evidence files and a QA report for every finding."""
    root = root or Path(tempfile.mkdtemp())
    found = v.select_findings(SPEC, ("defect",),
                              v.Revision(sha="c" * 40, patchset=2))
    for f in found:
        (root / f.id).mkdir(parents=True, exist_ok=True)
        (root / f.id / "out.txt").write_text("x")
        (root / f.id / "report.md").write_text(f"# QA report {f.id}")
    out = v.normalize({"findings": [
        {"id": f.id, "verdict": verdict, "method": "unmodified",
         "target": "rocky9", "summary": f"summary {f.id}",
         "steps": "ltvm create; repro.sh", "actual": "oops",
         "baseline": "passes", "origin": "change",
         "evidence": [f"{f.id}/out.txt"]}
        for f, verdict in zip(found, verdicts)]}, found, evidence_root=root)
    out["tested"] = {"sha": "c" * 40, "patchset": 2, "merged": False,
                     "branch": "master"}
    out["model"] = "opus"
    return out


