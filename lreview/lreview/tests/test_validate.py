class TestFindPosted:

    def _item(self):
        return _validation(["confirmed", "refuted"])["findings"][0]

    def test_matches_prefixed_comment(self):
        found = v.find_posted({"lustre/a.c": [_published()]}, SPEC,
                              self._item(), "c" * 40, TAG)
        assert found["id"] == "c1"

    @pytest.mark.parametrize("over", [
        {"line": 4},
        {"tag": "other"},
        {"in_reply_to": "x"},
        {"commit_id": "d" * 40},
        {"message": "(defect) something else"},
    ])
    def test_rejects_other_comments(self, over):
        assert v.find_posted({"lustre/a.c": [_published(**over)]}, SPEC,
                             self._item(), "c" * 40, TAG) is None

    def test_newest_of_two_reposts(self):
        old = _published(id="old")
        new = _published(id="new", updated="2026-11-25 10:00:00.000000000")
        found = v.find_posted({"lustre/a.c": [new, old]}, SPEC,
                              self._item(), "c" * 40, TAG)
        assert found["id"] == "new"

    def test_gerrit_finding_uses_its_comment_id(self):
        item = {"file": "x.c", "gerrit_id": "g1", "line": 5,
                "reviewed_patchset": 1, "reviewed_commit": "a" * 40}
        assert v.find_posted({}, {}, item, "c" * 40, TAG) == {
            "id": "g1", "line": 5, "patch_set": 1, "commit_id": "a" * 40}

    def test_replies_grouped_by_revision(self):
        validation = _validation(["confirmed", "refuted"])
        validation["findings"][1].update(gerrit_id="g2",
                                         reviewed_commit="a" * 40)
        groups, unmatched = v.plan_replies(
            {"lustre/a.c": [_published()]}, SPEC, validation, "c" * 40, TAG)
        assert unmatched == []
        assert set(groups) == {"c" * 40, "a" * 40}
        [reply] = groups["a" * 40]["lustre/b.c"]
        assert reply["in_reply_to"] == "g2"
        assert reply["_id"] == "F2"

    def test_range_comment_matched_by_end_line(self):
        spec = {"comments": {"x.c": [
            {"range": {"start_line": 1, "end_line": 4},
             "message": "(defect) span", "unresolved": True}]}}
        item = {"file": "x.c", "comment_index": 0}
        published = {"x.c": [_published(line=4, message="(defect) span")]}
        assert v.find_posted(published, spec, item, "c" * 40, TAG)


class TestRunValidation:

    @pytest.fixture
    def setup(self, tmp_path, monkeypatch):
        repo = tmp_path / "repo"
        repo.mkdir()
        results = tmp_path / "results"
        results.mkdir()
        worktree = tmp_path / "wt"
        worktree.mkdir()
        config = BatchConfig(repo=repo, results_dir=results,
                             worktrees_dir=tmp_path / "wts")
        destroyed = []
        monkeypatch.setattr(v, "destroy_owned_vms",
                            lambda owner: destroyed.append(owner) or ["vm1"])
        monkeypatch.setattr(v, "owned_vms", lambda owner: ([], []))
        return config, worktree, destroyed

    def test_collects_verdicts_and_evidence(self, setup, monkeypatch):
        config, worktree, destroyed = setup
        seen = {}

        def fake_run(cmd, cwd, log_path, timeout, env, stdin, stall):
            seen.update(cmd=cmd, env=env, timeout=timeout, stall=stall)
            log_path.write_text("")
            (cwd / "validation" / "F1").mkdir(parents=True)
            (cwd / "validation" / "F1" / "output.txt").write_text("oops")
            (cwd / "validation" / "F1" / "report.md").write_text("# r")
            (cwd / "validation.json").write_text(json.dumps({
                "target": "rocky9", "vms": ["bl1-lrv-64086"],
                "findings": [{"id": "F1", "verdict": "confirmed",
                              "method": "fail_loc", "summary": "oops",
                              "evidence": ["F1/output.txt"]}]}))
            return 0

        monkeypatch.setattr("lreview.runner._run_agent", fake_run)
        change = _change()
        found = v.select_findings(SPEC, ("defect",))
        vcfg = v.ValidateConfig(timeout=100, stall_timeout=50)
        record = v.run_validation(config, vcfg, change, worktree, found)

        assert record["status"] == "done"
        assert record["error"] is None
        assert record["counts"]["confirmed"] == 1
        assert record["counts"]["inconclusive"] == 1  # F2: no entry
        assert record["vms_destroyed"] == ["vm1"]
        assert destroyed == [v.owner_id(change)]
        saved = json.loads((config.results_dir / record["json"]).read_text())
        assert saved["evidence_dir"] == record["dir"]
